#!/usr/bin/env python
# Generates includes/abbreviations.md (Python-Markdown "abbr" definitions) from
# the abbreviations table in docs/introduction/abbreviations.md. The file is
# auto-appended to every page via pymdownx.snippets so abbreviations get
# hover tooltips site-wide.
#
# Usage:
#     python utils/build_glossary.py [--check]

import argparse
import re
import sys
from pathlib import Path

SOURCE = Path("docs/introduction/abbreviations.md")
TARGET = Path("includes/abbreviations.md")

# Abbreviations that collide with ordinary words or page codes and would get
# wrong tooltips all over the site.
EXCLUDE = {"IN", "EX", "SW", "TC", "CO", "ST", "CH", "A/T", "M/T", "MAX", "MIN", "NO", "No.", "STD", "TEMP", "w/", "w/o"}
ROW = re.compile(r"^\|\s*\*\*(?P<abbr>[^*]+)\*\*\s*\|\s*(?P<meaning>[^|]+?)\s*\|\s*$")


def build():
    lines = []
    for line in SOURCE.read_text().splitlines():
        match = ROW.match(line)
        if not match:
            continue
        abbr = match.group("abbr").strip()
        meaning = match.group("meaning").strip()
        # subscript markup (B~1~) cannot be matched in running text
        if "~" in abbr or abbr in EXCLUDE or len(abbr) < 2:
            continue
        lines.append(f"*[{abbr}]: {meaning}")
    header = "<!-- Generated by utils/build_glossary.py from docs/introduction/abbreviations.md; do not edit. -->\n"
    return header + "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Build the abbreviation glossary include.")
    parser.add_argument("--check", action="store_true", help="exit 1 if the include is out of date")
    args = parser.parse_args()
    content = build()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            print(f"{TARGET} is out of date; run utils/build_glossary.py")
            sys.exit(1)
        print(f"{TARGET} is up to date")
        return
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content)
    print(f"wrote {TARGET} ({content.count(chr(10)) - 1} abbreviations)")


if __name__ == "__main__":
    main()
